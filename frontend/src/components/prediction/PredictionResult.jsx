function PredictionResult({ prediction }) {
  if (!prediction) {
    return null
  }

  const probability =
    Number(prediction.attrition_probability || 0) * 100

  const isHighRisk =
    prediction.attrition_prediction === 1

  const riskLabel =
    prediction.risk_recommendation || 'Unknown Risk'

  return (
    <section
      aria-labelledby="prediction-result-title"
      className="mt-8 space-y-6"
    >
      <div>
        <p className="text-sm font-medium text-brand-600">
          Prediction Result
        </p>

        <h2
          id="prediction-result-title"
          className="mt-1 text-xl font-bold text-slate-900"
        >
          Employee Attrition Risk
        </h2>
      </div>

      <div className="grid gap-4 md:grid-cols-3">
        <MetricCard
          label="Attrition Probability"
          value={`${probability.toFixed(2)}%`}
        />

        <MetricCard
          label="Prediction"
          value={
            isHighRisk
              ? 'Attrition Risk'
              : 'No Attrition'
          }
        />

        <MetricCard
          label="Decision Threshold"
          value={`${(
            Number(prediction.selected_threshold || 0) * 100
          ).toFixed(0)}%`}
        />
      </div>

      <section className="rounded-xl border border-slate-200 bg-white p-6">
        <div className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
          <div>
            <h3 className="font-semibold text-slate-900">
              Risk Recommendation
            </h3>

            <p className="mt-1 text-sm text-slate-500">
              Business interpretation of the model decision.
            </p>
          </div>

          <span
            className={`inline-flex w-fit rounded-full px-3 py-1.5 text-sm font-semibold ${
              isHighRisk
                ? 'bg-red-100 text-red-700'
                : 'bg-emerald-100 text-emerald-700'
            }`}
          >
            {riskLabel}
          </span>
        </div>
      </section>

      <section className="rounded-xl border border-slate-200 bg-white p-6">
        <h3 className="font-semibold text-slate-900">
          Model Information
        </h3>

        <div className="mt-5 grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
          <InfoItem
            label="Prediction ID"
            value={prediction.prediction_id}
          />

          <InfoItem
            label="Model Version"
            value={prediction.model_version}
          />

          <InfoItem
            label="Feature Version"
            value={prediction.feature_version}
          />

          <InfoItem
            label="Inference Latency"
            value={`${Number(
              prediction.latency_ms || 0,
            ).toFixed(2)} ms`}
          />
        </div>
      </section>

      <section className="rounded-xl border border-slate-200 bg-white p-6">
        <div>
          <h3 className="font-semibold text-slate-900">
            Engineered Features
          </h3>

          <p className="mt-1 text-sm text-slate-500">
            Features generated by the V3 prediction pipeline.
          </p>
        </div>

        <div className="mt-5 grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
          {Object.entries(
            prediction.engineered_features || {},
          ).map(([name, value]) => (
            <div
              key={name}
              className="rounded-lg bg-slate-50 p-4"
            >
              <p className="text-xs font-medium text-slate-500">
                {formatFeatureName(name)}
              </p>

              <p className="mt-1 text-lg font-semibold text-slate-900">
                {formatFeatureValue(value)}
              </p>
            </div>
          ))}
        </div>
      </section>
    </section>
  )
}

function MetricCard({ label, value }) {
  return (
    <article className="rounded-xl border border-slate-200 bg-white p-5">
      <p className="text-sm text-slate-500">
        {label}
      </p>

      <p className="mt-2 text-2xl font-bold text-slate-900">
        {value}
      </p>
    </article>
  )
}

function InfoItem({ label, value }) {
  return (
    <div>
      <p className="text-xs font-medium uppercase tracking-wide text-slate-400">
        {label}
      </p>

      <p className="mt-1 break-words text-sm font-medium text-slate-800">
        {value ?? '—'}
      </p>
    </div>
  )
}

function formatFeatureName(name) {
  return name.replace(
    /([A-Z])/g,
    ' $1',
  ).trim()
}

function formatFeatureValue(value) {
  if (typeof value === 'number') {
    return Number.isInteger(value)
      ? value
      : value.toFixed(3)
  }

  return String(value)
}

export default PredictionResult